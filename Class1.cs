        private static void HandleStatFound(string statType, ulong playerId, string content)
        {
            // Enqueue the main logic to be run on the main game thread for thread safety.
            lock (mainThreadActions)
            {
                mainThreadActions.Enqueue(() =>
                {
                    Player player = GetPlayerBySteamId(playerId);
                    if (player == null)
                    {
                        if (EnableDetailedDebugLogging) AnnouncerLogger.Log($"[LogMonitor] Player with SteamID {playerId} not found.");
                        return;
                    }

                    string comment = null;
                    CommentaryPriority priority = CommentaryPriority.Medium;

                    switch (statType)
                    {
                        case "SOG":
                            if(int.TryParse(content, out int newSogCount))
                            {
                                int lastCount = lastSogCounts.ContainsKey(playerId) ? lastSogCounts[playerId] : 0;
                                if(newSogCount > lastCount)
                                {
                                    lastSogCounts[playerId] = newSogCount;
                                    comment = string.Format(shotPhrases[random.Next(shotPhrases.Count)], GetPlayerDisplayName(player));
                                    priority = CommentaryPriority.Medium;
                                }
                            }
                            break;
                        case "BLOCK":
                             if(int.TryParse(content, out int newBlockCount))
                            {
                                int lastCount = lastBlockCounts.ContainsKey(playerId) ? lastBlockCounts[playerId] : 0;
                                if(newBlockCount > lastCount)
                                {
                                    lastBlockCounts[playerId] = newBlockCount;
                                    comment = string.Format(blockedShotPhrases[random.Next(blockedShotPhrases.Count)], GetPlayerDisplayName(player));
                                    priority = CommentaryPriority.Medium;
                                }
                            }
                            break;
                        case "PASS":
                             if(int.TryParse(content, out int newPassCount))
                            {
                                int lastCount = lastPassCounts.ContainsKey(playerId) ? lastPassCounts[playerId] : 0;
                                if(newPassCount > lastCount)
                                {
                                    // We let the physics-based detection handle passes for now to get the receiver's name.
                                    lastPassCounts[playerId] = newPassCount;
                                }
                            }
                            break;
                        case "SAVEPERC":
                            var match = Regex.Match(content, @"\((\d+), \d+\)");
                            if(match.Success && int.TryParse(match.Groups[1].Value, out int newSaveCount))
                            {
                                int lastCount = lastSaveCounts.ContainsKey(playerId) ? lastSaveCounts[playerId] : 0;
                                if(newSaveCount > lastCount && player.Role.Value == PlayerRole.Goalie)
                                {
                                    lastSaveCounts[playerId] = newSaveCount;
                                    comment = string.Format(savePhrases[random.Next(savePhrases.Count)], GetPlayerDisplayName(player));
                                    priority = CommentaryPriority.High;
                                }
                            }
                            break;
                    }

                    if (comment != null)
                    {
                        EnqueueCommentary(comment, priority);
                    }
                });
            }
        }

        private static Player GetPlayerBySteamId(ulong steamId)
