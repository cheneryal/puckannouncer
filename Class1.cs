        }

        private static void InitializeRinkOrientation()
        {
            Goal[] goals = UnityEngine.Object.FindObjectsByType<Goal>(FindObjectsSortMode.None);
            if (goals == null || goals.Length < 2) return;

            var teamField = AccessTools.Field(typeof(Goal), "Team");
            if (teamField == null) { AnnouncerLogger.Log("Error: Could not access 'Team' field in Goal class."); return; }

            foreach (Goal goal in goals)
            {
                PlayerTeam team = (PlayerTeam)teamField.GetValue(goal);
                if (team == PlayerTeam.Red)
                {
                    redGoal = goal;
                    isRedTeamInPositiveZ = goal.transform.position.z > 0;
                }
                else if (team == PlayerTeam.Blue) { blueGoal = goal; }
            }

            if (redGoal != null && blueGoal != null)
            {
                isOrientationSet = true;
                AnnouncerLogger.Log($"Rink orientation set: Red Team is in Positive Z: {isRedTeamInPositiveZ}. Red Goal Z: {redGoal.transform.position.z}, Blue Goal Z: {blueGoal.transform.position.z}");
            }
        }

        private static string GetPlayerDisplayName(Player player)
        {
            if (player == null) return "a player";
            return player.Username.Value.ToString();
        }

        private static string GetZoneFromZ(float z_pos)
        {
            if (Mathf.Abs(z_pos) < 25.0f) return "Neutral";
            if (z_pos > 0) return isRedTeamInPositiveZ ? "Red" : "Blue";
            return isRedTeamInPositiveZ ? "Blue" : "Red";
        }

        private static string GetTeamZoneName(PlayerTeam team)
        {
            if (!isOrientationSet) return "Neutral";
            if (redGoal == null || blueGoal == null) return "Neutral";
            if (team == PlayerTeam.Red) return GetZoneFromZ(redGoal.transform.position.z);
            if (team == PlayerTeam.Blue) return GetZoneFromZ(blueGoal.transform.position.z);
            return "Neutral";
        }
        
        private static void EnqueueCommentary(string message, CommentaryPriority priority)
        {
            if (string.IsNullOrEmpty(message)) return;
            lock(commentaryQueue)
            {
                commentaryQueue.Enqueue(new CommentaryEvent(message, priority));
            }
        }

        internal static void RunCommentary(Puck puck)
        {
            if (puck == null || GameManager.Instance?.GameState == null || puckTargetingSystem == null) return;
            if (GameManager.Instance.GameState.Value.Phase != GamePhase.Playing) { return; }
            if (!isOrientationSet) InitializeRinkOrientation();

            var collisions = puck.GetPlayerCollisions();
            Player playerWithPuck = collisions?.LastOrDefault(c => c.Key != null && c.Key.Role.Value != PlayerRole.Goalie).Key;

            string comment = null;
            CommentaryPriority priority = CommentaryPriority.Low;
            
            if (!useLogFileDetection)
            {
                if (puck.ShotSpeed > shotSpeedThreshold && !isPuckTravelingAfterShot && lastPlayerWithPuck != null)
                {
                    Vector3 shotDirection = puck.Rigidbody.linearVelocity.normalized;
                    bool headedTowardsNet = puckTargetingSystem.IsHeadedTowardsOpponentNet(shotDirection, lastPlayerWithPuck.Team.Value);

                    if (headedTowardsNet)
                    {
                        comment = string.Format(shotPhrases[random.Next(shotPhrases.Count)], GetPlayerDisplayName(lastPlayerWithPuck));
                        EnqueueCommentary(comment, CommentaryPriority.Medium);
                        isPuckTravelingAfterShot = true;
                        isOffNetShot = false;
                        potentialShooter = lastPlayerWithPuck;
                        shotTime = Time.time;
                    }
                    else
                    {
                        isPuckTravelingAfterShot = true;
                        isOffNetShot = true;
                        potentialShooter = lastPlayerWithPuck;
                        shotTime = Time.time;
                    }

                    try
                    {
                        var shotSpeedField = AccessTools.Field(typeof(Puck), "<ShotSpeed>k__BackingField");
                        if (shotSpeedField != null) shotSpeedField.SetValue(puck, 0f);
                    }
                    catch (Exception e) { AnnouncerLogger.Log($"Error resetting ShotSpeed: {e.Message}"); }
                }
            }

            int currentPlayerId = playerWithPuck != null ? playerWithPuck.GetInstanceID() : -1;
            int lastPlayerId = lastPlayerWithPuck != null ? lastPlayerWithPuck.GetInstanceID() : -1;

            if (isWaitingForFaceoffWin && playerWithPuck != null)
            {
                comment = $"{GetPlayerDisplayName(playerWithPuck)} wins the draw!";
                EnqueueCommentary(comment, CommentaryPriority.Medium);
                isWaitingForFaceoffWin = false;
            }
            else if (isPuckTravelingAfterShot && !useLogFileDetection)
            {
                var goalieCollision = collisions?.LastOrDefault(c => c.Key != null && c.Key.Role.Value == PlayerRole.Goalie);
                if (goalieCollision.Value.Key != null && potentialSaver == null)
                {
                    potentialSaver = goalieCollision.Value.Key;
                }
                else
                {
                    var playerCollision = collisions?.LastOrDefault(c => c.Key != null && c.Key.Role.Value != PlayerRole.Goalie);
                    if (playerCollision.Value.Key != null && potentialShooter != null && playerCollision.Value.Key.Team.Value != potentialShooter.Team.Value)
                    {
                        comment = string.Format(blockedShotPhrases[random.Next(blockedShotPhrases.Count)], GetPlayerDisplayName(playerCollision.Value.Key));
                        EnqueueCommentary(comment, CommentaryPriority.Medium);
                        ResetShotState();
                    }
                }

                if (comment == null && Time.time - shotTime > saveCheckDelay)
                {
                    if (potentialSaver != null)
                    {
                        comment = string.Format(savePhrases[random.Next(savePhrases.Count)], GetPlayerDisplayName(potentialSaver));
                        EnqueueCommentary(comment, CommentaryPriority.High);
                        ResetShotState();
                    }
                    else if (isOffNetShot)
                    {
                        comment = string.Format(wideShotPhrases[random.Next(wideShotPhrases.Count)], GetPlayerDisplayName(potentialShooter));
                        EnqueueCommentary(comment, CommentaryPriority.Medium);
                        ResetShotState();
                    }
                }

                if (puck.PredictedSpeed < shotSpeedThreshold / 2) ResetShotState();
            }
            else if (playerWithPuck == null && !wasPuckFreeInLastFrame) { /* Puck became free */ }
            else if (playerWithPuck != null && wasPuckFreeInLastFrame)
            {
                bool isPass = lastPlayerWithPuck != null && playerWithPuck.Team.Value == lastPlayerWithPuck.Team.Value && playerWithPuck.GetInstanceID() != lastPlayerWithPuck.GetInstanceID();

                if (isPass)
                {
                    comment = string.Format(passPhrases[random.Next(passPhrases.Count)], GetPlayerDisplayName(lastPlayerWithPuck), GetPlayerDisplayName(playerWithPuck));
                    EnqueueCommentary(comment, CommentaryPriority.Low);
                }
            }
            else if (playerWithPuck != null && !wasPuckFreeInLastFrame && currentPlayerId != lastPlayerId)
            {
                if (playerWithPuck.Team.Value == lastPlayerWithPuck.Team.Value)
                {
                    comment = string.Format(passPhrases[random.Next(passPhrases.Count)], GetPlayerDisplayName(lastPlayerWithPuck), GetPlayerDisplayName(playerWithPuck));
                    EnqueueCommentary(comment, CommentaryPriority.Low);
                }
            }
            else if (playerWithPuck != null && currentPlayerId == lastPlayerId)
            {
                string currentZone = GetZoneFromZ(puck.transform.position.z);
                string previousZone = GetZoneFromZ(lastPuckPosition.z);
                
                if (currentZone != previousZone && !hasMadeAnnouncementThisPossession)
                {
                    string defensiveZone = GetTeamZoneName(playerWithPuck.Team.Value);

                    if (previousZone == defensiveZone && currentZone == "Neutral")
                    {
                        comment = string.Format(defensiveZoneClearPhrases[random.Next(defensiveZoneClearPhrases.Count)], GetPlayerDisplayName(playerWithPuck));
                        priority = CommentaryPriority.Medium;
                    }
                    else if (previousZone == "Neutral" && currentZone != "Neutral" && currentZone != defensiveZone)
                    {
                        comment = $"{GetPlayerDisplayName(playerWithPuck)} {string.Format(zoneEntryPhrases[random.Next(zoneEntryPhrases.Count)], "", "blue line")}";
                        priority = CommentaryPriority.Medium;
                    }
                    else if (previousZone != "Neutral" && currentZone != "Neutral" && previousZone != currentZone)
                    {
                         comment = $"{GetPlayerDisplayName(playerWithPuck)} {string.Format(zoneEntryPhrases[random.Next(zoneEntryPhrases.Count)], "", "center line")}";
                         priority = CommentaryPriority.Medium;
                    }
                    if(comment != null) EnqueueCommentary(comment, priority);
                }
                else if (Mathf.Abs(playerWithPuck.transform.position.x) > 20f)
                {
                    if (boardBattleStartTime == 0f) { boardBattleStartTime = Time.time; }
                    else if (!isAnnouncingBoardBattle && Time.time - boardBattleStartTime > boardBattleTimeThreshold)
                    {
                        comment = boardBattlePhrases[random.Next(boardBattlePhrases.Count)];
                        EnqueueCommentary(comment, CommentaryPriority.Low);
                        isAnnouncingBoardBattle = true;
                    }
                }
                else if (!hasMadeAnnouncementThisPossession && Time.time - possessionStartTime > minPossessionTimeForAnnouncement)
                {
                    string phrase = possessionPhrases[random.Next(possessionPhrases.Count)];
                    if (phrase.Contains("{1}"))
                    {
                        string teamName = playerWithPuck.Team.Value == PlayerTeam.Blue ? "Blue" : "Red";
                        comment = string.Format(phrase, GetPlayerDisplayName(playerWithPuck), teamName);
                    }
                    else
                    {
                        comment = string.Format(phrase, GetPlayerDisplayName(playerWithPuck));
                    }
                    EnqueueCommentary(comment, CommentaryPriority.Low);
                    lastAnnouncedPlayerId = currentPlayerId;
                    hasMadeAnnouncementThisPossession = true; // Set here to prevent spamming possession calls
                }
            }

            if (playerWithPuck == null || Mathf.Abs(playerWithPuck.transform.position.x) < 20f) { boardBattleStartTime = 0f; isAnnouncingBoardBattle = false; }
            
            // --- STATE UPDATE LOGIC (at the end of the frame) ---
            if (playerWithPuck != null && (wasPuckFreeInLastFrame || (currentPlayerId != lastPlayerId)))
            {
                possessionStartTime = Time.time;
                hasMadeAnnouncementThisPossession = false;
            }
            else if (playerWithPuck == null && !wasPuckFreeInLastFrame)
            {
                lastPossessionChangeTime = Time.time;
            }

            if (playerWithPuck != null && currentPlayerId != lastPlayerId)
            {
                lastPlayerWithPuck = playerWithPuck;
            }

            if (lastPlayerWithPuck != null)
            {
                lastPlayerWithPuckTeam = lastPlayerWithPuck.Team.Value;
            }

            wasPuckFreeInLastFrame = (playerWithPuck == null);
        }

        private static void ProcessCommentaryQueue()
        {
            if (commentaryCooldown > 0)
            {
                commentaryCooldown -= Time.fixedDeltaTime;
            }

            lock (commentaryQueue)
            {
                if (commentaryQueue.Count > 0)
                {
                    var nextEvent = commentaryQueue.Peek();
                    
                    bool canOverride = (nextEvent.Priority > lastBroadcastPriority && nextEvent.Priority > CommentaryPriority.Low);

                    if (commentaryCooldown <= 0 || canOverride)
                    {
                        var eventToBroadcast = commentaryQueue.Dequeue();
                        Broadcast(eventToBroadcast.Message, eventToBroadcast.Priority);
                    }
                }
            }
        }


        private static void Broadcast(string message, CommentaryPriority priority = CommentaryPriority.Low)
        {
            if (string.IsNullOrEmpty(message) || message == lastBroadcastMessage) return;
            AnnouncerLogger.Log($"BROADCAST: {message}");
            if (NetworkManager.Singleton?.IsClient != true) return;

            if (BroadcastToChat) {
                if(UIChat.Instance != null) UIChat.Instance.AddChatMessage(message);
            }
            else { 
                if(UIToastManager.Instance != null) UIToastManager.Instance.ShowToast("announcer_commentary", message, 3f); 
            }

            lastBroadcastMessage = message;
            commentaryCooldown = CooldownDurations[priority];
            lastBroadcastPriority = priority;
            if (priority > CommentaryPriority.Low) {
                 hasMadeAnnouncementThisPossession = true;
            }
        }

        private static void ResetShotState()
        {
            isPuckTravelingAfterShot = false;
            isOffNetShot = false;
            potentialShooter = null;
            potentialSaver = null;
            shotTime = 0f;
        }

        private static void ResetPlayState()
        {
            ResetShotState();
            lastPlayerWithPuck = null;
            lastAnnouncedPlayerId = -1;
            isWaitingForFaceoffWin = false;
            wasPuckFreeInLastFrame = true;
            boardBattleStartTime = 0f;
            isAnnouncingBoardBattle = false;
            hasMadeAnnouncementThisPossession = false;
            lastPlayerWithPuckTeam = PlayerTeam.None;
            lastBroadcastMessage = "";
            lastSogCounts.Clear();
            lastBlockCounts.Clear();
            lastSaveCounts.Clear();
            lastPassCounts.Clear();
        }

