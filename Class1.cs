    /// <summary>
    /// A simple static logger to write AnnouncerMod specific messages to its own file.
    /// </summary>
    internal static class AnnouncerLogger
    {
        private static StreamWriter logWriter;

        static AnnouncerLogger()
        {
            try
            {
                string puckGamePath = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
                string logDirectory = Path.Combine(puckGamePath, "Logs");

                if (!Directory.Exists(logDirectory))
                {
                    Directory.CreateDirectory(logDirectory);
                }

                string logFilePath = Path.Combine(logDirectory, "AnnouncerMod.log");
                // Set append to false to overwrite the log file on each startup
                logWriter = new StreamWriter(logFilePath, false) { AutoFlush = true };
                Log("Logger initialized successfully.");
            }
            catch (Exception e)
            {
                Debug.LogError($"[AnnouncerMod] Failed to initialize file logger: {e.Message}");
                logWriter = null;
            }
        }

        public static void Log(string message)
        {
            Debug.Log($"[AnnouncerMod] {message}");
            logWriter?.WriteLine($"[{DateTime.Now:yyyy-MM-dd HH:mm:ss}] {message}");
        }

        public static void Close()
        {
            logWriter?.Close();
            logWriter = null;
        }
    }

    /// <summary>
    /// Monitors the Puck.log file for stat changes from the server-side stats mod.
    /// This provides a more reliable way to detect events like shots, saves, and blocks.
    /// </summary>
    internal static class LogFileMonitor
    {
        // Action to be invoked when a stat is found in the log file.
        public static event Action<string, ulong, string> OnStatFound;
        
        private static long lastPosition = 0;
        private static string logFilePath;
        
        // Regex to parse the specific log entries generated by the server-side stats mod.
        private static readonly Regex statRegex = new Regex(@"oomtm450_stats(SOG|SAVEPERC|BLOCK|TAKEAWAY|TURNOVER|PASS)(\d{17}).*Content : (.*)$", RegexOptions.Compiled);
        private static Timer fileCheckTimer;

        public static void Initialize()
        {
            try
            {
                string puckGamePath = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
                logFilePath = Path.Combine(puckGamePath, "Logs", "Puck.log");

                if (!File.Exists(logFilePath))
                {
                    AnnouncerLogger.Log($"Puck.log not found at {logFilePath}. Log monitoring will not start.");
                    return;
                }
                
                // Read to the end of the file on start to avoid processing old logs
                using (var fs = new FileStream(logFilePath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
                {
                    lastPosition = fs.Length;
                }

                // FileSystemWatcher can be unreliable on some systems, so we use a timer to periodically check.
                fileCheckTimer = new Timer(CheckForLogChanges, null, 0, 250); // Check every 250ms

                AnnouncerLogger.Log("LogFileMonitor initialized and watching Puck.log.");
            }
            catch (Exception e)
            {
                AnnouncerLogger.Log($"Failed to initialize LogFileMonitor: {e.Message}");
            }
        }
        
        private static void CheckForLogChanges(object state)
        {
            try
            {
                if (!File.Exists(logFilePath)) return;

                long currentLength = new FileInfo(logFilePath).Length;
                if (currentLength > lastPosition)
                {
                    ReadNewLogEntries();
                }
                else if (currentLength < lastPosition)
                {
                    // Log file was likely reset
                    lastPosition = 0;
                }
            }
            catch (Exception e)
            {
                AnnouncerLogger.Log($"Error checking Puck.log for changes: {e.Message}");
            }
        }

        private static void ReadNewLogEntries()
        {
            try
            {
                using (var fs = new FileStream(logFilePath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
                {
                    fs.Seek(lastPosition, SeekOrigin.Begin);
                    using (var reader = new StreamReader(fs))
                    {
                        string line;
                        while ((line = reader.ReadLine()) != null)
                        {
                            ParseLine(line);
                        }
                        lastPosition = fs.Position;
                    }
                }
            }
            catch (Exception e)
            {
                AnnouncerLogger.Log($"Error reading Puck.log: {e.Message}");
            }
        }

        private static void ParseLine(string line)
        {
            Match match = statRegex.Match(line);
            if (match.Success)
            {
                string statType = match.Groups[1].Value;
                if (ulong.TryParse(match.Groups[2].Value, out ulong playerId))
                {
                    string content = match.Groups[3].Value.Trim();
                    AnnouncerLogger.Log($"[LogMonitor] Found Stat: Type={statType}, PlayerID={playerId}, Content={content}");
                    OnStatFound?.Invoke(statType, playerId, content);
                }
            }
        }

        public static void Stop()
        {
            fileCheckTimer?.Dispose();
            fileCheckTimer = null;
            AnnouncerLogger.Log("LogFileMonitor stopped.");
        }
    }

    /// <summary>
    /// Component attached to the puck to determine if it's heading towards a net.
    /// </summary>
    internal class PuckTargetingSystem : MonoBehaviour
    {
        private readonly float MAX_DISTANCE = 50f;
        private readonly LayerMask _goalTriggerLayerMask = LayerMask.GetMask("Goal Trigger");
        private readonly float PUCK_RADIUS_OFFSET = 0.06f;
        private readonly Vector3 TOP_RAY_OFFSET = new Vector3(0, 0.08f, 0);
        private readonly Vector3 BOTTOM_RAY_OFFSET = new Vector3(0, 0.01f, 0);

        internal bool IsHeadedTowardsOpponentNet(Vector3 direction, PlayerTeam shooterTeam)
        {
            if (direction == Vector3.zero) return false;

            Vector3 currentPosition = transform.position;
            Vector3 leftVector = currentPosition + (Quaternion.Euler(0, -90, 0) * direction * PUCK_RADIUS_OFFSET);
            Vector3 rightVector = currentPosition + (Quaternion.Euler(0, 90, 0) * direction * PUCK_RADIUS_OFFSET);

            RaycastHit hit;

            bool hitDetected =
                Physics.Raycast(new Ray(leftVector + TOP_RAY_OFFSET, direction), out hit, MAX_DISTANCE, _goalTriggerLayerMask, QueryTriggerInteraction.Collide) ||
                Physics.Raycast(new Ray(rightVector + TOP_RAY_OFFSET, direction), out hit, MAX_DISTANCE, _goalTriggerLayerMask, QueryTriggerInteraction.Collide) ||
                Physics.Raycast(new Ray(leftVector + BOTTOM_RAY_OFFSET, direction), out hit, MAX_DISTANCE, _goalTriggerLayerMask, QueryTriggerInteraction.Collide) ||
                Physics.Raycast(new Ray(rightVector + BOTTOM_RAY_OFFSET, direction), out hit, MAX_DISTANCE, _goalTriggerLayerMask, QueryTriggerInteraction.Collide);

            if (hitDetected)
            {
                GoalTrigger goalTrigger = hit.collider.GetComponent<GoalTrigger>();
                if (goalTrigger != null)
                {
                    var goalField = AccessTools.Field(typeof(GoalTrigger), "goal");
                    if (goalField != null)
                    {
                        Goal goalObject = (Goal)goalField.GetValue(goalTrigger);
                        if (goalObject != null)
                        {
                            var goalTeamField = AccessTools.Field(typeof(Goal), "Team");
                            if (goalTeamField != null)
                            {
                                PlayerTeam team = (PlayerTeam)goalTeamField.GetValue(goalObject);
                                return team != shooterTeam;
                            }
                        }
                    }
                }
            }
            return false;
        }
    }


